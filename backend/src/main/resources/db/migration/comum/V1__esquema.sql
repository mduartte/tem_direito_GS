-- =====================================================================
-- Tem Direito · esquema do banco (V1)
-- Roda igual no Oracle (19c+/23ai/Free) e no H2 em modo Oracle.
-- Tipos Oracle: NUMBER, VARCHAR2, CLOB, TIMESTAMP; booleanos em NUMBER(1).
--
-- Princípio de LGPD que guia o modelo: a TRIAGEM é anônima (código T-xxxx,
-- bairro, pessoas, renda por pessoa, benefícios). Nada de nome, CPF, NIS ou
-- telefone. A CONTA do cidadão é opcional, separada, e guarda o telefone
-- só como hash (para login) e cifrado (para SMS, se a pessoa pedir).
-- =====================================================================

-- Catálogo dos 29 benefícios que o motor avalia.
CREATE TABLE beneficio (
    id            VARCHAR2(20)  PRIMARY KEY,           -- id usado no resultado (bpci, tar...)
    chave_regra   VARCHAR2(20)  NOT NULL,              -- chave nos parâmetros (bpcI, tar...)
    nome          VARCHAR2(120) NOT NULL,
    orgao         VARCHAR2(120) NOT NULL,
    abrangencia   VARCHAR2(20)  NOT NULL,              -- Federal, Estadual, Municipal
    ativo_unidade NUMBER(1)     DEFAULT 1 NOT NULL,    -- a unidade orienta este benefício? (tela E4)
    ordem         NUMBER(3)     NOT NULL
);

-- Cada versão de cada regra. Publicar = nova linha PUBLICADA e a anterior ARQUIVADA.
-- A chave "_geral" guarda o salário mínimo usado em todos os cálculos.
CREATE TABLE regra_versao (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave         VARCHAR2(20)  NOT NULL,
    versao        NUMBER(5)     NOT NULL,
    parametros    CLOB          NOT NULL,              -- JSON com os limites (formato do REGRAS_PADRAO)
    situacao      VARCHAR2(12)  NOT NULL,              -- PUBLICADA, RASCUNHO, ARQUIVADA
    autor         VARCHAR2(120),
    revisor       VARCHAR2(120),
    motivo        VARCHAR2(400),
    criada_em     TIMESTAMP     NOT NULL,
    publicada_em  TIMESTAMP,
    CONSTRAINT uk_regra_versao UNIQUE (chave, versao, situacao)
);

-- Histórico de auditoria das publicações ("quem mudou, quem revisou e por quê").
CREATE TABLE historico_regra (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo        VARCHAR2(160) NOT NULL,              -- "BPC Idoso v4"
    chave         VARCHAR2(20)  NOT NULL,
    versao        NUMBER(5)     NOT NULL,
    autor         VARCHAR2(120) NOT NULL,
    revisor       VARCHAR2(120) NOT NULL,
    motivo        VARCHAR2(400),
    mudancas      CLOB,                                 -- JSON: [[campo, antes, depois], ...]
    data_hora     TIMESTAMP     NOT NULL
);

-- Documentos-base e frase de cada passo do Kit do Direito (editável na tela C3).
CREATE TABLE kit_passo (
    id            VARCHAR2(20)  PRIMARY KEY,           -- cras, inss, luz, mae, casa
    titulo        VARCHAR2(160) NOT NULL,
    onde          VARCHAR2(200),
    documentos    CLOB          NOT NULL,              -- JSON: lista de documentos
    atualizado_em TIMESTAMP,
    atualizado_por VARCHAR2(120)
);

-- Bairros do território do piloto e as faixas de CEP de cada um.
CREATE TABLE bairro (
    nome          VARCHAR2(80)  PRIMARY KEY,
    cep_faixas    VARCHAR2(200) NOT NULL,              -- "04930-04949;05840-05859" (5 primeiros dígitos)
    lat           NUMBER(10,6)  NOT NULL,
    lng           NUMBER(10,6)  NOT NULL,
    familias_cad  NUMBER(9)
);

-- Pontos de atendimento: CRAS, UBS, farmácias credenciadas e Defensoria.
CREATE TABLE ponto_atendimento (
    id            VARCHAR2(20)  PRIMARY KEY,
    tipo          VARCHAR2(20)  NOT NULL,              -- CRAS, UBS, Farmácia, Defensoria
    nome          VARCHAR2(160) NOT NULL,
    endereco      VARCHAR2(240) NOT NULL,
    bairro        VARCHAR2(80),
    horario       VARCHAR2(120),
    telefone      VARCHAR2(40),
    obs           VARCHAR2(160),
    lat           NUMBER(10,6)  NOT NULL,
    lng           NUMBER(10,6)  NOT NULL,
    ativo         NUMBER(1)     DEFAULT 1 NOT NULL
);

-- Triagem anônima. "chave_hash" protege as atualizações: só o aparelho que criou a triagem pode mudá-la.
CREATE TABLE triagem (
    codigo        VARCHAR2(12)  PRIMARY KEY,           -- T-5231
    chave_hash    VARCHAR2(64),
    criada_em     TIMESTAMP     NOT NULL,
    atualizada_em TIMESTAMP     NOT NULL,
    bairro        VARCHAR2(80)  NOT NULL,
    pessoas       NUMBER(3)     NOT NULL,
    renda_pc      NUMBER(12,2)  NOT NULL,              -- renda por pessoa (arredondada)
    beneficios    VARCHAR2(400),                       -- ids separados por vírgula
    etapa         VARCHAR2(20)  NOT NULL,              -- triagem, kit, agendado, atendido, conseguiu, travado
    etapa_texto   VARCHAR2(200),
    falta         VARCHAR2(120),                       -- documento que faltou
    autorizou     NUMBER(1)     DEFAULT 0 NOT NULL,    -- família autorizou o CRAS a mandar aviso
    canal         VARCHAR2(30),                        -- App, App · voz, Site
    regras_usadas VARCHAR2(1000),                      -- "BPC Idoso v3, Tarifa Social v4" (auditoria)
    obs_cras      VARCHAR2(1000),                      -- observação interna da equipe
    conta_id      NUMBER(19),
    demo          NUMBER(1)     DEFAULT 0 NOT NULL     -- dado de demonstração (não veio de um aparelho)
);
CREATE INDEX ix_triagem_criada ON triagem (criada_em);
CREATE INDEX ix_triagem_bairro ON triagem (bairro);
CREATE INDEX ix_triagem_etapa ON triagem (etapa);

-- Linha do tempo de cada triagem (o que aparece em "Linha do tempo" no painel).
CREATE TABLE triagem_evento (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triagem_codigo VARCHAR2(12) NOT NULL,
    texto         VARCHAR2(300) NOT NULL,
    alerta        NUMBER(1)     DEFAULT 0 NOT NULL,
    data_hora     TIMESTAMP     NOT NULL,
    CONSTRAINT fk_evento_triagem FOREIGN KEY (triagem_codigo) REFERENCES triagem (codigo) ON DELETE CASCADE
);
CREATE INDEX ix_evento_triagem ON triagem_evento (triagem_codigo);

-- Situação de cada benefício para a família (Meus direitos): fui, faltou, pedido, consegui, negado.
CREATE TABLE triagem_beneficio_status (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triagem_codigo VARCHAR2(12) NOT NULL,
    beneficio_id  VARCHAR2(20)  NOT NULL,
    situacao      VARCHAR2(20)  NOT NULL,
    atualizado_em TIMESTAMP     NOT NULL,
    CONSTRAINT fk_status_triagem FOREIGN KEY (triagem_codigo) REFERENCES triagem (codigo) ON DELETE CASCADE,
    CONSTRAINT uk_status UNIQUE (triagem_codigo, beneficio_id)
);

-- Lembrete de ir ao atendimento. O aviso sai na véspera às 19h (tarefa agendada).
CREATE TABLE lembrete (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triagem_codigo VARCHAR2(12) NOT NULL,
    data_ida      DATE          NOT NULL,
    canal         VARCHAR2(10)  NOT NULL,              -- app, sms, ambos
    local_nome    VARCHAR2(160) NOT NULL,
    local_endereco VARCHAR2(240),
    documentos    VARCHAR2(600),
    enviado_em    TIMESTAMP,
    criado_em     TIMESTAMP     NOT NULL,
    CONSTRAINT fk_lembrete_triagem FOREIGN KEY (triagem_codigo) REFERENCES triagem (codigo) ON DELETE CASCADE
);

-- Avisos que a família vê no app (e por SMS, se pediu): lembrete, retorno, aviso do CRAS.
CREATE TABLE notificacao (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triagem_codigo VARCHAR2(12) NOT NULL,
    tipo          VARCHAR2(20)  NOT NULL,              -- LEMBRETE, RETORNO_7, RETORNO_30, AVISO_CRAS, PRAZO
    texto         VARCHAR2(500) NOT NULL,
    canal         VARCHAR2(10)  NOT NULL,              -- app, sms
    criada_em     TIMESTAMP     NOT NULL,
    lida_em       TIMESTAMP,
    CONSTRAINT fk_notif_triagem FOREIGN KEY (triagem_codigo) REFERENCES triagem (codigo) ON DELETE CASCADE
);
CREATE INDEX ix_notif_triagem ON notificacao (triagem_codigo);

-- Conta opcional do cidadão: entra só com o celular e um código por SMS.
CREATE TABLE conta_cidadao (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR2(60),                        -- como quer ser chamada (opcional)
    telefone_hash VARCHAR2(64)  NOT NULL UNIQUE,       -- SHA-256 com sal: permite login sem guardar o número
    telefone_cifrado VARCHAR2(200),                    -- AES-GCM: só para enviar SMS, se a pessoa pediu
    telefone_mascara VARCHAR2(20) NOT NULL,            -- (11) 9 ••••-1234
    aceite_termos NUMBER(1)     NOT NULL,
    aceite_sensiveis NUMBER(1)  NOT NULL,              -- LGPD art. 11: renda e saúde só para avaliar direitos
    aviso_cras    NUMBER(1)     DEFAULT 1 NOT NULL,
    aviso_novos   NUMBER(1)     DEFAULT 1 NOT NULL,
    aviso_prazos  NUMBER(1)     DEFAULT 1 NOT NULL,
    criada_em     TIMESTAMP     NOT NULL
);

-- Códigos de verificação (SMS do cidadão e segunda etapa do painel). Expiram em 10 minutos.
CREATE TABLE codigo_verificacao (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destino_hash  VARCHAR2(64)  NOT NULL,
    finalidade    VARCHAR2(20)  NOT NULL,              -- CIDADAO, PAINEL
    codigo_hash   VARCHAR2(64)  NOT NULL,
    dados         VARCHAR2(400),
    expira_em     TIMESTAMP     NOT NULL,
    tentativas    NUMBER(2)     DEFAULT 0 NOT NULL,
    usado         NUMBER(1)     DEFAULT 0 NOT NULL
);

-- Unidade (CRAS) e sua configuração inicial (telas E2 e E4).
CREATE TABLE unidade (
    id            NUMBER(19)    PRIMARY KEY,
    nome          VARCHAR2(160) NOT NULL,
    telefone      VARCHAR2(40),
    endereco      VARCHAR2(240),
    sem_agendamento NUMBER(1)   DEFAULT 1 NOT NULL,
    horarios      CLOB,                                -- JSON
    territorio    CLOB,                                -- JSON: bairros atendidos
    servicos      CLOB,                                -- JSON
    mensagem_retorno VARCHAR2(400),
    retencao_dias NUMBER(4)     DEFAULT 90 NOT NULL,   -- triagens individuais são apagadas depois disso
    resumo_semanal NUMBER(1)    DEFAULT 1 NOT NULL,
    configurada   NUMBER(1)     DEFAULT 0 NOT NULL
);

-- Usuários do painel (CRAS, coordenação, gestor de regras).
CREATE TABLE usuario_painel (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR2(160) NOT NULL UNIQUE,
    nome          VARCHAR2(120) NOT NULL,
    perfil        VARCHAR2(20)  NOT NULL,              -- ATENDENTE, COORDENACAO, GESTOR
    senha_hash    VARCHAR2(100),                       -- BCrypt; nulo enquanto o convite não foi aceito
    situacao      VARCHAR2(20)  NOT NULL,              -- ATIVO, CONVIDADO, INATIVO
    unidade_id    NUMBER(19),
    criado_em     TIMESTAMP     NOT NULL
);

-- Computadores lembrados por 30 dias na verificação em duas etapas (tela E5).
CREATE TABLE dispositivo_confiavel (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    NUMBER(19)    NOT NULL,
    token_hash    VARCHAR2(64)  NOT NULL,
    expira_em     TIMESTAMP     NOT NULL
);

-- Pedidos de organizações que querem usar o painel (tela E1).
CREATE TABLE solicitacao_acesso (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_org      VARCHAR2(40)  NOT NULL,
    nome_org      VARCHAR2(160) NOT NULL,
    cnpj          VARCHAR2(20),
    municipio     VARCHAR2(120) NOT NULL,
    responsavel   VARCHAR2(120) NOT NULL,
    cargo         VARCHAR2(120),
    email         VARCHAR2(160) NOT NULL,
    telefone      VARCHAR2(40),
    situacao      VARCHAR2(20)  NOT NULL,              -- RECEBIDA, APROVADA, RECUSADA
    criada_em     TIMESTAMP     NOT NULL
);

-- Números agregados por bairro e dia. Ficam depois que as triagens individuais são apagadas (retenção LGPD).
CREATE TABLE agregado_diario (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia           DATE          NOT NULL,
    bairro        VARCHAR2(80)  NOT NULL,
    triagens      NUMBER(9)     NOT NULL,
    encaminhados  NUMBER(9)     NOT NULL,
    conseguiram   NUMBER(9)     NOT NULL,
    CONSTRAINT uk_agregado UNIQUE (dia, bairro)
);

-- Registro de cada execução das automações (aparece no painel em Configurações → Automações).
CREATE TABLE execucao_tarefa (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa        VARCHAR2(40)  NOT NULL,
    inicio        TIMESTAMP     NOT NULL,
    fim           TIMESTAMP,
    itens         NUMBER(9)     DEFAULT 0 NOT NULL,
    detalhe       VARCHAR2(1000),
    manual        NUMBER(1)     DEFAULT 0 NOT NULL
);
